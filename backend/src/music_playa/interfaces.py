from pathlib import Path
from typing import Protocol

from music_playa.models import PlaybackMode, Track


class AudioEngine(Protocol):
    @property
    def position(self) -> float: ...

    @property
    def duration(self) -> float: ...

    @property
    def is_playing(self) -> bool: ...

    @property
    def volume(self) -> float: ...

    def load(self, path: Path) -> float: ...

    def play(self) -> None: ...

    def pause(self) -> None: ...

    def stop(self) -> None: ...

    def seek(self, position: float) -> None: ...

    def set_volume(self, volume: float) -> None: ...


class PlaybackListener(Protocol):
    def on_progress(self, position: float, duration: float) -> None: ...

    def on_track(self, track: Track | None) -> None: ...


class Player(Protocol):
    @property
    def current(self) -> Track | None: ...

    @property
    def position(self) -> float: ...

    @property
    def duration(self) -> float: ...

    @property
    def volume(self) -> float: ...

    @property
    def mode(self) -> PlaybackMode: ...

    @mode.setter
    def mode(self, mode: PlaybackMode) -> None: ...

    def play(self) -> None: ...

    def pause(self) -> None: ...

    def stop(self) -> None: ...

    def select(self, track: Track) -> None: ...

    def next(self) -> None: ...

    def previous(self) -> None: ...

    def seek(self, position: float) -> None: ...

    def set_volume(self, volume: float) -> None: ...

    def add_listener(self, listener: PlaybackListener) -> None: ...


class Library(Protocol):
    @property
    def tracks(self) -> list[Track]: ...

    def cover(self, track: Track) -> bytes | None: ...


class Visualizer(Protocol):
    def bands(self) -> list[float]: ...

    def wave(self) -> list[float]: ...
